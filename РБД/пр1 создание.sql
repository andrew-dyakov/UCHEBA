DROP TYPE IF EXISTS fio_type, passport_type, address_type CASCADE;
DROP DOMAIN IF EXISTS fio_type_nn, passport_type_nn, address_type_nn CASCADE;

CREATE TYPE fio_type AS (
    last_name   varchar(50),
    first_name  varchar(50),
    middle_name varchar(50)   
);

CREATE DOMAIN fio_type_nn AS fio_type
CHECK (
    (VALUE).last_name IS NOT NULL 
    AND trim((VALUE).last_name) <> ''
    AND length(trim((VALUE).last_name)) >= 2
    AND (VALUE).first_name IS NOT NULL 
    AND trim((VALUE).first_name) <> ''
    AND length(trim((VALUE).first_name)) >= 2
    AND ((VALUE).middle_name IS NULL OR length(trim((VALUE).middle_name)) >= 2)
);

CREATE TYPE passport_type AS (
    series     varchar(4),
    number     varchar(6),
    issued_by  varchar(100),   
    issue_date date
);

CREATE DOMAIN passport_type_nn AS passport_type
CHECK (
    (VALUE).series IS NOT NULL AND length((VALUE).series) = 4
    AND (VALUE).number IS NOT NULL AND length((VALUE).number) = 6
    AND (VALUE).issue_date <= CURRENT_DATE
);


CREATE TYPE address_type AS (
    postal_code varchar(50),
    country     varchar(50),   
    city        varchar(50),
    street      varchar(100),
    building    varchar(50),
    apartment   varchar(50)
);

CREATE DOMAIN address_type_nn AS address_type
CHECK (
    (VALUE).country IS NOT NULL AND trim((VALUE).country) <> ''
    AND (VALUE).city IS NOT NULL AND trim((VALUE).city) <> ''
    AND (VALUE).street IS NOT NULL AND trim((VALUE).street) <> ''
    AND (VALUE).building IS NOT NULL AND trim((VALUE).building) <> ''
);





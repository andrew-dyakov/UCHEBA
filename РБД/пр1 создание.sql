CREATE TABLE IF NOT EXISTS hotel (
    id          int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(50)   NOT NULL,
    country_id  integer       NOT NULL,
    city_id     integer       NOT NULL,
    stars       smallint      NOT NULL DEFAULT 3
        CONSTRAINT chk_hotel_stars CHECK (stars BETWEEN 1 AND 5),
    full_address address_type_nn NOT NULL,
    description text,
    meal_type_id integer,

    CONSTRAINT chk_hotel_name_length CHECK (length(name) >= 3)
);


COMMENT ON TABLE hotel IS 'Отели с категорией звездности и расположением';
COMMENT ON COLUMN hotel.full_address IS 'Полный почтовый адрес отеля (составной тип)';


CREATE TABLE IF NOT EXISTS client (
    id             int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name      fio_type_nn NOT NULL,
    passport_data  passport_type_nn NOT NULL UNIQUE,
    email          varchar(50) NOT NULL UNIQUE,
    login          varchar(50) NOT NULL UNIQUE,
    password       varchar(50) NOT NULL,
    birth_date     date        NOT NULL,

    CONSTRAINT chk_client_email_format CHECK (
        email ~ '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$'
    ),
    CONSTRAINT chk_client_age CHECK (
        birth_date <= CURRENT_DATE - INTERVAL '18 years'
    )
);
COMMENT ON TABLE client IS 'Зарегистрированные клиенты туристического агентства';
COMMENT ON COLUMN client.full_name IS 'ФИО клиента (составной тип)';
COMMENT ON COLUMN client.passport_data IS 'Паспортные данные: серия, номер, кем выдан, дата выдачи';
COMMENT ON COLUMN client.birth_date IS 'Дата рождения для возрастных ограничений';



CREATE TABLE IF NOT EXISTS employee (
    id          int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name   fio_type_nn NOT NULL,
    position_id integer     NOT NULL,
    login       varchar(50) NOT NULL UNIQUE,
    password    varchar(50) NOT NULL,
    is_active   boolean     NOT NULL DEFAULT true,

    CONSTRAINT chk_employee_login_length CHECK (length(login) >= 4)
);
COMMENT ON TABLE employee IS 'Сотрудники компании (менеджеры, операторы)';
COMMENT ON COLUMN employee.full_name IS 'ФИО сотрудника (составной тип)';

CREATE TABLE IF NOT EXISTS service (
    id                int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              varchar(50)  NOT NULL,
    service_type      varchar(50)  NOT NULL DEFAULT 'tour'
        CHECK (service_type IN ('tour', 'flight', 'hotel', 'insurance')),
    country_id        integer      NOT NULL,
    departure_city    varchar(50),
    supplier_id       integer      NOT NULL,
    description       text,
    airline_id        integer      NOT NULL,
    tour_operator_id  integer      NOT NULL,

    CONSTRAINT chk_service_flight_departure CHECK (
        (service_type != 'flight') OR (departure_city IS NOT NULL)
    )
);

COMMENT ON TABLE service IS 'Абстрактный турпродукт (карточка тура/авиабилета/отеля/страховки)';
COMMENT ON COLUMN service.service_type IS 'Тип услуги: тур, авиабилет, отель, страховка';


CREATE TABLE IF NOT EXISTS customer_order (
    id           int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at   timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    client_id    integer     NOT NULL,
    employee_id  integer     NOT NULL,
    status_id    integer     NOT NULL,
    paid_at      timestamptz DEFAULT CURRENT_TIMESTAMP,
    total_amount numeric(10,2) NOT NULL DEFAULT 0,

    CONSTRAINT chk_order_paid_after_created CHECK (
        paid_at IS NULL OR paid_at >= created_at
    ),
    CONSTRAINT chk_order_total_positive CHECK (total_amount >= 0)
);
COMMENT ON TABLE customer_order IS 'Шапка заказа клиента – документ, фиксирующий состав заказа и итоговую сумму';
COMMENT ON COLUMN customer_order.created_at IS 'Дата и время создания заказа (по умолчанию текущее)';
COMMENT ON COLUMN customer_order.paid_at IS 'Дата фактической оплаты (NULL, если не оплачен)';

CREATE TABLE IF NOT EXISTS payment (
    id             int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id       integer     NOT NULL,
    payment_date   timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    amount         numeric(10,2) NOT NULL,
    status_id      integer     NOT NULL,
    payment_type_id integer     NOT NULL,

    CONSTRAINT chk_payment_amount_positive CHECK (amount > 0)
);

COMMENT ON TABLE payment IS 'Запись об оплате заказа. Один заказ может иметь несколько платежей (частичная оплата)';
COMMENT ON COLUMN payment.status_id IS 'Ссылка на статус платежа (успех/неуспех/в обработке)';

CREATE TABLE IF NOT EXISTS purchase (
    id            int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      integer     NOT NULL,
    purchase_date timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    supplier_id   integer     NOT NULL,
    cost_amount   numeric(10,2) NOT NULL,

    CONSTRAINT chk_purchase_cost_positive CHECK (cost_amount > 0)
);

COMMENT ON TABLE purchase IS 'Документ выкупа у поставщика – фиксирует себестоимость для расчёта маржи';
COMMENT ON COLUMN purchase.cost_amount IS 'Себестоимость (закупочная цена)';

CREATE TABLE IF NOT EXISTS refund (
    id          int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id  integer     NOT NULL,
    refund_date timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    amount      numeric(10,2) NOT NULL,

    CONSTRAINT chk_refund_amount_positive CHECK (amount > 0)
);

COMMENT ON TABLE refund IS 'Возврат денежных средств клиенту по платежу';


CREATE TABLE IF NOT EXISTS phone (
    id           int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id    integer     NOT NULL,
    phone_number varchar(14) NOT NULL UNIQUE,

    CONSTRAINT chk_phone_number_format CHECK (
        phone_number ~ '^\+?[0-9\-\(\)\s]{10,15}$'
    )
);

COMMENT ON TABLE phone IS 'Многозначный атрибут клиента – телефоны для связи';
COMMENT ON COLUMN phone.phone_number IS 'Номер телефона в международном формате';

CREATE TABLE IF NOT EXISTS order_item (
    service_id integer NOT NULL,
    order_id   integer NOT NULL,
    quantity   integer NOT NULL DEFAULT 1,
    price      numeric(10,2) NOT NULL,
    PRIMARY KEY (service_id, order_id),

    CONSTRAINT chk_order_item_quantity_positive CHECK (quantity > 0),
    CONSTRAINT chk_order_item_price_positive CHECK (price > 0)
);

COMMENT ON TABLE order_item IS 'Позиция заказа – слабая сущность, фиксирующая услуги и их количество в заказе. Цена сохраняется на момент продажи.';
COMMENT ON COLUMN order_item.quantity IS 'Количество единиц услуги (билетов, ночей)';
COMMENT ON COLUMN order_item.price IS 'Цена за единицу на момент продажи (защита от изменения прайса)';

CREATE TABLE IF NOT EXISTS purchase_item (
    service_id  integer NOT NULL,
    purchase_id integer NOT NULL,
    quantity    integer NOT NULL DEFAULT 1,
    cost_price  numeric(10,2) NOT NULL,
    PRIMARY KEY (service_id, purchase_id),

    CONSTRAINT chk_purchase_item_quantity_positive CHECK (quantity > 0),
    CONSTRAINT chk_purchase_item_cost_positive CHECK (cost_price > 0)
);

COMMENT ON TABLE purchase_item IS 'Позиция выкупа – детализация, что именно и по какой цене выкуплено у поставщика';

CREATE TABLE IF NOT EXISTS service_hotel (
    service_id integer NOT NULL,
    hotel_id   integer NOT NULL,
    PRIMARY KEY (service_id, hotel_id)
);
COMMENT ON TABLE service_hotel IS 'Связка услуги и отеля (многие ко многим). Позволяет одному туру предлагать несколько отелей, а отелю участвовать в разных турах.';

CREATE TABLE IF NOT EXISTS categories (
    category_id SERIAL PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    parent_id   INT,  -- Ссылка на родительскую категорию
    CONSTRAINT fk_parent_category
    FOREIGN KEY (parent_id)
    REFERENCES categories(category_id)
    ON DELETE CASCADE
);

COMMENT ON TABLE categories IS 'Иерархический справочник категорий услуг (туров, перелётов, отелей)';
COMMENT ON COLUMN categories.parent_id IS 'ID родительской категории (NULL — корневая категория)';

CREATE TABLE IF NOT EXISTS user_logs (
    log_id SERIAL PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    user_id INT,
    event_data JSONB
);




